import { Schema, model } from "mongoose";
import { IInvoice } from "./invoice.interface";

const invoiceSchema = new Schema<IInvoice>(
  {
    invoiceNumber: { type: String },
    customer: { type: Schema.Types.ObjectId, ref: "customer" },
    pro: { type: Schema.Types.ObjectId, ref: "pro" },
    estimate: { type: Schema.Types.ObjectId, ref: "estimate" },
    estimateNumber: { type: String },
    workOrder: { type: Schema.Types.ObjectId, ref: "workorder" },
    workOrderNumber: { type: String },
    primaryTech: {
      id: { type: Schema.Types.ObjectId },
      staffId: String,
      name: String,
      email: String,
      avatar: String,
      staffLocation: String,
      role: String,
      employementStatus: String,
      group: String,
      status: String,
      commisionRange: Object,
    },
    secondaryTech: {
      id: { type: Schema.Types.ObjectId },
      staffId: String,
      name: String,
      email: String,
      avatar: String,
      role: String,
      employementStatus: String,
      group: String,
      status: String,
      commisionRange: Object,
    },
    channelManager: {
      id: { type: Schema.Types.ObjectId },
      staffId: String,
      name: String,
      email: String,
      employementStatus: String,
      avatar: String,
      role: String,
      group: String,
      status: String,
      commisionRange: Object,
    },
    parentLoginId: { type: Schema.Types.ObjectId, ref: "pro" },
    managerLoginId: { type: Schema.Types.ObjectId, ref: "staff" },
    billing_details: {
      customerName: String,
      customerType: String,
      firstName: String,
      lastName: String,
      email: String,
      phone: String,
      customerSince: Date,
      streetAddress: String,
      zip: String,
      city: String,
      state: String,
      paymentMethod: String,
      invoiceEmail: String,
      adminNotes: String,
      poNumber: String,
      customerCreditLimit: String,
      terms: String,
    },
    createdBy: String,
    createdByLoginId: { type: Schema.Types.ObjectId },
    createdFrom: { type: String, enum: ["workOrder", "estimate"] },
    jobTitle: String,
    jobDescription: String,
    status: {
      type: String,
      enum: [
        "temp",
        "draft",
        "partiallyPaid",
        "paid",
        "unpaid",
        "pending",
        "refunded",
        "modify",
        "voided",
      ],
    },
    images: [String],
    videos: [String],
    invoiceNotes: String,
    jobSiteNotes: String,
    techNotes: String,
    labourWarranty: Number,
    partsWarranty: Number,
    unpaidBalanceReminder: Number,
    products: [
      {
        productType: {
          type: String,
          enum: ["material", "pricebook", "labor", "custom"],
        },
        id: { type: Schema.Types.ObjectId, refPath: "products.ref" },
        itemId: String,
        ref: { type: String, enum: ["inventory", "pricebook", "staff"] },
        name: String,
        description: String,
        qty: { type: Number, required: true },
        units: String,
        role: { type: String, default: null },
        unitPrice: Number,
        costPrice: Number,
        subTotal: Number,
        image: String,
        productLocation: String,
      },
    ],
    transactions: {
      paidAmount: { type: Number, default: 0 },
      unpaidAmount: { type: Number },
      writeOffAmount: { type: Number, default: 0 },
      refundedAmount: { type: Number, default: 0 },
      creditAmount: { type: Number, default: 0 },
      usedCreditAmount: { type: Number, default: 0 },
      actualPaidAmount: { type: Number, default: 0 },
      availableForRefundRequests: { type: Number, default: 0 },
      transactionDate: { type: Date },
    },
    dueDate: { type: Date },
    agreedToTerms: { type: Boolean, default: false },
  },
  { timestamps: true }
).pre("save", function (next) {
  if (this.transactions) {
    this.transactions.actualPaidAmount =
      (this.transactions.paidAmount || 0) -
      (this.transactions.refundedAmount || 0) -
      (this.transactions.usedCreditAmount || 0);
  }
  next();
});

export const Invoice = model<IInvoice>("Invoice", invoiceSchema);
