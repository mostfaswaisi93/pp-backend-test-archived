import mongoose, { Document, Schema, model } from "mongoose";
import { IPayrollReport } from "./payroll-report.interface";

const payrollReportSchema = new Schema<IPayrollReport>(
  {
    startTime: { type: Date },
    endTime: { type: Date },
    prId: { type: String }, // AUTOGENERATED CODE FOR REPORT
    serIds: [
      { type: mongoose.Schema.Types.ObjectId, ref: "commisions_report" },
    ],
    salary: { type: Number, default: 0 },
    totalGrossSales: { type: Number, default: 0 },
    totalEarnings: { type: Number, default: 0 },
    totalCommission: { type: Number, default: 0 },
    bonus: { type: Number, default: 0 },
    spiff: { type: Number, default: 0 },
    reimbursable: { type: Number, default: 0 },
    status: { type: String, default: "STAFF DRAFT" },
    paymentStatus: { type: String, default: "pending" },
    paidOn: { type: Date },
    reportPath: { type: String },
    parentLoginId: { type: String }, // connecting the staff to report
  },
  { timestamps: true }
);

export const PayrollReport = model<IPayrollReport>(
  "PayrollReport",
  payrollReportSchema
);
